/**
 * Get all weather stations for a specific Austrian state
 */
export function getStationsByState(state: string): WeatherStation[] {
  return ALL_STATIONS
    .filter(s => s.state === state)
    .sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Get a weather station by its ID
 */
export function getStationById(id: string): WeatherStation {
  const station = ALL_STATIONS.find(s => s.id === id);
  if (!station) {
    throw new Error(`Station with ID ${id} not found`);
  }
  return station;
}

/**
 * Get multiple weather stations by their IDs
 */
export function getStationsByIds(ids: string[]): WeatherStation[] {
  return ids.map(id => getStationById(id));
}
